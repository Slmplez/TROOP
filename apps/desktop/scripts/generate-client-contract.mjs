import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import contract from "../contracts/execution.cjs";
import prettier from "prettier";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
function type(schema) {
  if (typeof schema === "string")
    return schema
      .split("|")
      .map((s) => ({ id: "number", count: "number", json: "unknown" })[s] ?? s)
      .join(" | ");
  if (schema.record) return `Record<string, ${type(schema.record)}>`;
  if (schema.items) return `Array<${type(schema.items)}>`;
  if (schema.values)
    return schema.values.map((v) => JSON.stringify(v)).join(" | ");
  return `{ ${Object.entries(schema.fields)
    .map(
      ([k, v]) =>
        `${JSON.stringify(k.replace(/\?$/, ""))}${k.endsWith("?") ? "?" : ""}: ${type(v)};`,
    )
    .join(" ")} }`;
}
const types =
  `// Generated by scripts/generate-client-contract.mjs. Do not edit.\n` +
  Object.entries(contract.types)
    .map(([name, schema]) => `export type ${name} = ${type(schema)};`)
    .join("\n") +
  `\nexport interface Requests {\n${Object.entries(contract.methods)
    .map(
      ([name, d]) =>
        `  ${JSON.stringify(name)}: { input: ${type(d.input)}; output: ${type(d.output)} };`,
    )
    .join("\n")}\n}\n`;
const signatures = {
  id: ["id", "{ id }"],
  turn: ["id", "{ turn_id: id }"],
  offset: ["offset = 0", "{ offset }"],
  events: ["id, before = null", "{ id, before }"],
  content: ["id, field", "{ id, field }"],
  none: ["", "{}"],
  object: ["input", "input"],
  messages: ["id, before = null", "id, before"],
};
const bindings = Object.entries(contract.methods)
  .map(([name, d]) => {
    const [args, wire] = signatures[d.mode];
    const value = name.startsWith("chat.")
      ? ({ id: "id", turn: "id", offset: "offset" }[d.mode] ?? wire)
      : wire;
    return `    ${d.bridge}: (${args}) => call("troop:${d.channel}", ${value}),`;
  })
  .join("\n");
const preloadPath = path.join(root, "src/preload.cjs");
if (
  !fs.readFileSync(preloadPath, "utf8").includes("// BEGIN EXECUTION CONTRACT")
)
  throw Error("Missing preload generation marker");
const preload = fs
  .readFileSync(preloadPath, "utf8")
  .replace(
    /\/\/ BEGIN EXECUTION CONTRACT[\s\S]*?\/\/ END EXECUTION CONTRACT/,
    `// BEGIN EXECUTION CONTRACT\n${bindings}\n    // END EXECUTION CONTRACT`,
  );
for (const [file, text] of [
  ["contracts/execution.d.ts", types],
  ["src/preload.cjs", preload],
]) {
  const target = path.join(root, file);
  const formatted = await prettier.format(text, { filepath: target });
  if (process.argv.includes("--check")) {
    if (
      !fs.existsSync(target) ||
      fs.readFileSync(target, "utf8").replace(/\r\n/g, "\n") !==
        formatted.replace(/\r\n/g, "\n")
    )
      throw Error(`Generated contract is stale: ${file}`);
  } else fs.writeFileSync(target, formatted);
}
